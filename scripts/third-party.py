#!/usr/bin/env python3
"""Third-party notices for what openKWL ships: the firmware image (Rust crates linked into it)
and the web UI on the SD card (npm packages bundled into app.js, the Geist fonts).

    scripts/third-party.py            writes THIRD_PARTY.md (overview, committed)
    scripts/third-party.py --full F   also writes F: every licence text, for release artifacts

Run it after changing dependencies (docs/DEVELOPMENT.md, Releasing). Needs mise, cargo and pnpm.
"""

import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LICENSE_FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def run(args, cwd):
    return subprocess.run(["mise", "exec", "--", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def license_texts(directory):
    """The licence files of a package, as (file name, text)."""
    out = []
    for name in sorted(os.listdir(directory)):
        if name.upper().startswith(LICENSE_FILES) and os.path.isfile(os.path.join(directory, name)):
            with open(os.path.join(directory, name), encoding="utf-8", errors="replace") as f:
                out.append((name, f.read().strip()))
    return out


def rust_crates():
    """Crates linked into the firmware: normal dependencies for the device target, not ours."""
    meta = json.loads(run(["cargo", "metadata", "--format-version", "1", "--filter-platform", "thumbv7m-none-eabi"], os.path.join(ROOT, "firmware")))
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), [meta["resolve"]["root"]]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    crates = []
    for pid in seen:
        p = packages[pid]
        if p["source"] is None:  # our own crates and the vendored serde-json-core
            if "vendor" not in p["manifest_path"]:
                continue
        crates.append({
            "name": p["name"],
            "version": p["version"],
            "license": p.get("license") or "see files",
            "url": p.get("repository") or "",
            "texts": license_texts(os.path.dirname(p["manifest_path"])),
        })
    return sorted(crates, key=lambda c: c["name"])


def npm_packages():
    """Production packages of the web UI (bundled into app.js)."""
    tree = json.loads(run(["pnpm", "list", "--prod", "--depth", "Infinity", "--json"], os.path.join(ROOT, "web")))
    found = {}

    def walk(deps):
        for name, d in (deps or {}).items():
            key = (name, d.get("version"))
            # Optional platform packages that aren't installed have no directory.
            if key not in found and d.get("path") and os.path.isfile(os.path.join(d["path"], "package.json")):
                found[key] = d["path"]
                walk(d.get("dependencies"))

    for project in tree:
        walk(project.get("dependencies"))
    packages = []
    for (name, version), path in found.items():
        with open(os.path.join(path, "package.json"), encoding="utf-8") as f:
            pkg = json.load(f)
        lic = pkg.get("license") or "see files"
        repo = pkg.get("repository")
        packages.append({
            "name": name,
            "version": version,
            "license": lic if isinstance(lic, str) else lic.get("type", "see files"),
            "url": (repo.get("url") if isinstance(repo, dict) else repo) or pkg.get("homepage") or "",
            "texts": license_texts(path),
        })
    return sorted(packages, key=lambda p: p["name"])


def fonts():
    path = os.path.join(ROOT, "web", "public", "fonts")
    return [{"name": "Geist, Geist Mono", "version": "", "license": "OFL-1.1", "url": "https://vercel.com/font", "texts": license_texts(path) or [("OFL.txt", open(os.path.join(path, "OFL.txt"), encoding="utf-8").read().strip())]}]


def table(items):
    rows = ["| Component | Version | Licence |", "|---|---|---|"]
    rows += [f"| {i['name']} | {i['version']} | {i['license']} |" for i in items]
    return "\n".join(rows)


def main():
    rust, npm, font = rust_crates(), npm_packages(), fonts()
    overview = f"""# Third-party components

openKWL ships code and fonts from other projects. All of them are under permissive licences
(MIT, Apache-2.0, BSD, 0BSD, Unicode, OFL); none is copyleft. The full licence texts come with
every release (`THIRD_PARTY_LICENSES.txt`, made by `scripts/third-party.py --full`).

Generated by `scripts/third-party.py`; don't edit by hand.

## In the firmware image ({len(rust)} crates)

{table(rust)}

## In the web UI on the SD card ({len(npm)} npm packages, and the fonts)

{table(npm + font)}
"""
    with open(os.path.join(ROOT, "THIRD_PARTY.md"), "w", encoding="utf-8") as f:
        f.write(overview)
    print(f"THIRD_PARTY.md: {len(rust)} crates, {len(npm)} npm packages, fonts")

    if "--full" in sys.argv:
        target = sys.argv[sys.argv.index("--full") + 1]
        parts = ["Third-party licences for openKWL (firmware image and web UI).\n"]
        for item in rust + npm + font:
            parts.append("=" * 78)
            parts.append(f"{item['name']} {item['version']}  ({item['license']})  {item['url']}".rstrip())
            parts.append("=" * 78)
            if not item["texts"]:
                parts.append(f"Licence: {item['license']}, copyright the {item['name']} authors ({item['url'] or 'see the package'}).")
                parts.append("The package carries no licence file; the standard texts are at the end of this file.\n")
            for name, text in item["texts"]:
                parts.append(f"--- {name} ---\n{text}\n")
        # Standard texts for packages that don't ship their own (taken from packages that do).
        standard = {}
        for item in rust + npm:
            for name, text in item["texts"]:
                upper = name.upper()
                if "APACHE" in upper and "Apache-2.0" not in standard:
                    standard["Apache-2.0"] = text
                elif upper.startswith("LICENSE-MIT") and "MIT" not in standard:
                    standard["MIT"] = text
        parts.append("=" * 78)
        parts.append("Standard licence texts (for the packages above without their own file)")
        parts.append("=" * 78)
        for spdx, text in standard.items():
            parts.append(f"--- {spdx} ---\n{text}\n")
        with open(target, "w", encoding="utf-8") as f:
            f.write("\n".join(parts) + "\n")
        print(f"{target}: {os.path.getsize(target) // 1024} KB")


if __name__ == "__main__":
    main()
